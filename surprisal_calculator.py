import gradio as gr
from surprisal import AutoHuggingFaceModel
import matplotlib.pyplot as plt

model = AutoHuggingFaceModel.from_pretrained('GroNLP/gpt2-small-dutch')

def compute_surprisal(sentence):
    plt.close('all')
    # Get surprisal values for each token
    [surprisal] = model.surprise(sentence)

    if not surprisal:
        return 0.0, None

    # Compute total surprisal
    mean_surprisal = (surprisal[0:, 'word'])/len(surprisal)

    # Plot per-word surprisal
    fig, ax = plt.subplots(figsize=(10, 4))
    for result in model.surprise(sentence):
      fig, ax = result.lineplot(fig, ax)

    # ax.set_title("Per-Word Surprisal", pad=15)
    ax.set_xlabel("Token")
    ax.set_ylabel("Surprisal")
    fig.tight_layout()

    return round(float(mean_surprisal),2), fig

with gr.Blocks() as demo:
    gr.Markdown("## Surprisal Visualizer\nTyp een zin in om de voorspelbaarheid per woord te berekenen.")

    sentence = gr.Textbox(
        label="Jouw meest verrassende zin:",
        placeholder="De kat zat op de mat."
    )

    total = gr.Number(label="Gemiddelde Surprisal-waarde per woord")
    plot = gr.Plot(label="Woord-per-woord Surprisal")

    sentence.submit(
        compute_surprisal,
        inputs=sentence,
        outputs=[total, plot]
    )

demo.launch(share=True, debug=False)